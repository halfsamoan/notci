"""Generate native CSS and GJS token module from the shared JSON definition."""

import argparse
import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
TOKENS = ROOT / "docs/design/design-tokens.json"
EXT = ROOT / "extension"


def render() -> dict[Path, str]:
    data = json.loads(TOKENS.read_text(encoding="utf-8"))
    template = (EXT / "stylesheet.css.in").read_text(encoding="utf-8")
    for family, values in data.items():
        if not isinstance(values, dict):
            continue
        for name, value in values.items():
            template = template.replace("{{" + family + "." + name + "}}", str(value))
    if "{{" in template:
        raise ValueError("Unresolved design token in CSS template")
    # St scales only pt (not px) font sizes with GNOME's Large Text / text-scaling-factor.
    # Tokens stay in px for design work; 1px = 0.75pt at 96 dpi keeps scale 1.0 identical.
    template = re.sub(r"font-size: (\d+(?:\.\d+)?)px",
                      lambda m: f"font-size: {float(m.group(1)) * 0.75:g}pt", template)
    module = "// Generated by tools/build_design.py; edit docs/design/design-tokens.json.\n"
    module += "export const DESIGN = " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n"
    return {EXT / "stylesheet.css": template, EXT / "designTokens.js": module}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render()
    if args.check:
        mismatches = [str(path.relative_to(ROOT)) for path, content in generated.items()
                      if not path.exists() or path.read_text(encoding="utf-8") != content]
        if mismatches:
            print("Generated design files differ:", ", ".join(mismatches))
            return 1
    else:
        for path, content in generated.items():
            path.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
